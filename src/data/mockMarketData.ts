// Helper to generate realistic candles
function generateCandles(basePrice: number, count: number = 30, volatility: number = 0.015) {
  const candles = [];
  let currentPrice = basePrice * (1 - volatility * (count / 4));
  const now = Date.now();
  const stepMs = 3600 * 1000 * 24; // 1 day steps

  for (let i = 0; i < count; i++) {
    const timeStr = new Date(now - (count - i) * stepMs).toISOString().split('T')[0];
    const change = (Math.random() - 0.48) * volatility * currentPrice;
    const open = currentPrice;
    const close = Math.max(0.01, open + change);
    const high = Math.max(open, close) + Math.random() * volatility * currentPrice * 0.7;
    const low = Math.min(open, close) - Math.random() * volatility * currentPrice * 0.7;
    const volume = Math.floor(Math.random() * 5000000 + 1000000);

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    currentPrice = close;
  }
  return candles;
}

function generateSparkline(candles: { close: number }[]) {
  return candles.map(c => c.close);
}

